import { createTypedCatalog, typedAction } from '../../src/typed-catalog.js';
import type { InferSchema, TypedActionPayload } from '../../src/typed-catalog.js';

const typed = createTypedCatalog({ id: 'typed-test', version: '1', components: { text: { tag: 'p', properties: {}, text: true } }, actions: {
  save: { payload: { type: 'object', properties: { title: { type: 'string' }, count: { type: 'integer' }, mode: { type: 'string', enum: ['draft', 'final'] } }, required: ['title', 'mode'], additionalProperties: false } },
  clear: { payload: { type: 'null' } },
} }, { type: 'object', properties: { query: { type: 'string' }, tags: { type: 'array', items: { type: 'string' } } }, required: ['query'], additionalProperties: false });

typed.action('save', { title: 'Report', mode: 'draft', count: 3 });
typedAction(typed, 'clear', null);
// @ts-expect-error Undeclared action names cannot be generated by the typed factory.
typed.action('remove', null);
// @ts-expect-error The standalone helper preserves the same declared action set.
typedAction(typed, 'remove', null);
// @ts-expect-error Required payload fields remain required.
typed.action('save', { mode: 'draft' });
// @ts-expect-error Integer schemas infer number, not a coerced numeric string.
typedAction(typed, 'save', { title: 'Report', mode: 'draft', count: '3' });
// @ts-expect-error Enum schemas preserve literal values.
typed.action('save', { title: 'Report', mode: 'other' });
// @ts-expect-error A payload is explicit, including null for clear.
typed.action('clear');
// @ts-expect-error Closed object payloads reject unknown literal properties.
typed.action('save', { title: 'Report', mode: 'draft', executable: true });

const parsed = typed.parseState({ query: 'hello' });
if (parsed.ok) {
  parsed.value.query.toUpperCase();
  parsed.value.tags?.map(tag => tag.toUpperCase());
  // @ts-expect-error State values retain inferred types.
  parsed.value.query.toFixed();
  // @ts-expect-error Undeclared state members are absent.
  parsed.value.unknown;
}
type Save = TypedActionPayload<typeof typed.definition, 'save'>;
const save: Save = { title: 'Report', mode: 'final' };
void save;
type NullableNumber = InferSchema<{ readonly anyOf: readonly [{ readonly type: 'number' }, { readonly type: 'null' }] }>;
const nullable: NullableNumber = null;
void nullable;
// @ts-expect-error A const anyOf infers only its declared alternatives.
const invalid: NullableNumber = false;
void invalid;
