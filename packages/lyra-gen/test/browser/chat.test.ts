const formIsland = '```lyra\n<stack id="answer"><text id="intro">Review the answer.</text>'
  + '<input id="note" label="Review note" bindings={{"value":"/note"}} /></stack>\n```\n';
const apps: ReturnType<typeof mountInteractiveChat>[] = [];

afterEach(() => { for (const app of apps.splice(0)) app.dispose(); });

function query<T extends Element = HTMLElement>(root: ParentNode, selector: string): T {
  const element = root.querySelector<T>(selector);
  expect(element !== null, `Expected ${selector}`).to.equal(true);
  if (!element) throw new Error(`Missing ${selector}`);
  return element;
}
function activeElement(): Element | null {
  let active = document.activeElement;
  while (active?.shadowRoot?.activeElement) active = active.shadowRoot.activeElement;
  return active;
}
async function mount(overrides: Partial<Parameters<typeof mountInteractiveChat>[1]> = {}) {
  const wrapper = await fixture<HTMLElement>(html`<div><button>Outside focus target</button><div style="inline-size:360px;max-inline-size:100%"></div></div>`);
  const root = query<HTMLElement>(wrapper, 'div');
  const app = mountInteractiveChat(root, {
    sources: new Map(), canAsk: () => true, onAsk: () => {}, onSource: () => {},
    provenance: 'Generated by the assistant', onResume: () => {}, onRetry: () => {}, onCancel: () => {}, ...overrides,
  });
  apps.push(app);
  app.viewport.style.blockSize = '240px';
  await Promise.all([app.transcript.updateComplete, app.viewport.updateComplete, app.suggestions.updateComplete]);
  return { app, wrapper, root };
}
async function ready(app: ReturnType<typeof mountInteractiveChat>, index = 0): Promise<LyraGenViewElement> {
  await waitUntil(() => (app.transcript.shadowRoot?.querySelectorAll('lr-gen-view').length ?? 0) > index,
    'Generated view mounted through renderPart', { timeout: 10000 });
  const view = app.transcript.shadowRoot!.querySelectorAll<LyraGenViewElement>('lr-gen-view')[index]!;
  await view.updateComplete;
  await waitUntil(() => view.status === 'ready' && view.parentElement?.getAttribute('aria-busy') === 'false', 'Generated controls committed', { timeout: 10000 });
  return view;
}
function nativeInput(view: LyraGenViewElement): HTMLInputElement {
  return query<HTMLInputElement>(query(view.shadowRoot!, 'lr-input').shadowRoot!, 'input');
}
function shell(view: LyraGenViewElement): HTMLElement { return view.parentElement!; }
function completionCount(): number { return sinkTexts().filter(text => text === 'Generated content ready.').length; }

it('streams into renderPart without moving focus; real user edits and one readiness announcement survive prose deltas', async () => {
  const { app, wrapper } = await mount();
  const outside = query<HTMLButtonElement>(wrapper, 'button');
  await focusByKeyboard(outside);
  const announcements = completionCount();
  app.push('Introduction\n```lyra\n<stack id="answer"><text id="intro">Review the answer.</text>');
  await app.transcript.updateComplete;
  expect(app.transcript.shadowRoot!.querySelector('[aria-busy="true"]') !== null).to.equal(true);
  expect(completionCount()).to.equal(announcements);
  app.push('<input id="note" label="Review note" bindings={{"value":"/note"}} /></stack>\n```\n');
  const view = await ready(app);
  expect(activeElement() === outside).to.equal(true);
  expect(shell(view).getAttribute('aria-busy')).to.equal('false');
  await waitUntil(() => completionCount() === announcements + 1);
  const input = nativeInput(view);
  await focusByKeyboard(input);
  await sendKeys({ type: 'Keep my review' });
  expect(input.value).to.equal('Keep my review');
  const document = view.document;
  app.push('A following explanation is arriving.');
  await app.transcript.updateComplete;
  await twoFrames();
  expect((await ready(app)) === view).to.equal(true);
  expect(view.document === document).to.equal(true);
  expect(nativeInput(view) === input).to.equal(true);
  expect(activeElement() === input).to.equal(true);
  expect(input.value).to.equal('Keep my review');
  app.finish();
  await app.transcript.updateComplete;
  expect(completionCount()).to.equal(announcements + 1);
});

it('keeps a released reader position while an island grows and follows growth after returning to the end', async () => {
  const { app } = await mount();
  app.transcript.contentMode = 'plain';
  app.push('Earlier message. '.repeat(300) + '\n```lyra\n<text id="growing">');
  await app.transcript.updateComplete;
  const scroll = query<HTMLElement>(app.viewport.shadowRoot!, '[part="scroll"]');
  const atEnd = () => scroll.scrollHeight - scroll.clientHeight - scroll.scrollTop <= 2;
  await waitUntil(atEnd, 'Follow mode remains at the end during initial growth', { timeout: 5000 });
  await focusByKeyboard(scroll);
  await sendKeys({ press: 'Home' });
  await waitUntil(() => !app.viewport.follow, 'Keyboard scroll releases follow mode', { timeout: 5000 });
  await waitUntil(() => scroll.scrollTop <= 1, 'Keyboard Home scroll settles before measuring reader position', { timeout: 5000 });
  const position = scroll.scrollTop;
  app.push('Growing island text. '.repeat(300) + '</text>\n```\n');
  await ready(app);
  await twoFrames();
  expect(scroll.scrollTop).to.be.closeTo(position, 1);
  expect(app.viewport.follow).to.equal(false);
  app.viewport.scrollToBottom({ behavior: 'auto' });
  await waitUntil(atEnd, 'Returning to the end restores follow mode');
  app.push('A new paragraph after the island. '.repeat(300));
  await app.transcript.updateComplete;
  await waitUntil(atEnd, 'Follow mode stays at the end as prose grows', { timeout: 5000 });
  expect(app.viewport.follow).to.equal(true);
});

it('shows a host resume control while retaining a complete safe form and its edited value', async () => {
  let resumes = 0;
  const { app } = await mount({ onResume: () => { resumes++; } });
  app.push(formIsland + '```lyra\n<text id="pending">');
  const view = await ready(app);
  const input = nativeInput(view);
  await focusByKeyboard(input);
  await sendKeys({ type: 'Retained through interruption' });
  app.interrupt(true);
  await app.transcript.updateComplete;
  const button = Array.from(app.transcript.shadowRoot!.querySelectorAll<HTMLButtonElement>('button'))
    .find(candidate => candidate.textContent === 'Resume')!;
  expect(button !== undefined).to.equal(true);
  await focusByKeyboard(button);
  await sendKeys({ press: 'Enter' });
  expect(resumes).to.equal(1);
  expect(app.controller.snapshot.status).to.equal('streaming');
  app.push('The remainder</text>\n```\n'); app.finish();
  await ready(app, 1);
  expect((await ready(app)) === view).to.equal(true);
  expect(nativeInput(view).value).to.equal('Retained through interruption');
});

it('shows explicit retry after cancellation and replaces only the incomplete tail', async () => {
  let retries = 0;
  let cancellations = 0;
  const { app } = await mount({ onRetry: () => { retries++; }, onCancel: () => { cancellations++; } });
  app.push(formIsland + '```lyra\n<text id="pending">');
  const view = await ready(app);
  app.cancel();
  await app.transcript.updateComplete;
  expect(cancellations).to.equal(1);
  const button = Array.from(app.transcript.shadowRoot!.querySelectorAll<HTMLButtonElement>('button'))
    .find(candidate => candidate.textContent === 'Retry')!;
  await focusByKeyboard(button);
  await sendKeys({ press: 'Enter' });
  expect(retries).to.equal(1);
  app.push('```lyra\n<text id="replacement">Retried answer</text>\n```\n'); app.finish();
  await ready(app, 1);
  expect((await ready(app)) === view).to.equal(true);
  expect(app.controller.snapshot.islands[1]?.document?.root.id).to.equal('replacement');
});

it('renders viewer-owned citation labels and removes activation after authorization is revoked', async () => {
  const sources = new Map([['report', { id: 'report', label: 'Reviewed report' }]]);
  const selected: string[] = [];
  const { app } = await mount({ sources, onSource: source => { selected.push(source.id); } });
  app.push('```lyra\n<stack id="sources"><citation id="allowed" sourceId="report" label="Model claim" />'
    + '<citation id="missing" sourceId="private" label="Pretend verified" /></stack>\n```\n'); app.finish();
  const view = await ready(app);
  const badge = query(view.shadowRoot!, 'lr-citation-badge');
  expect((badge as HTMLElement & { label: string }).label).to.equal('Reviewed report');
  expect(view.shadowRoot!.textContent).to.contain('Source unavailable');
  await focusByKeyboard(query<HTMLButtonElement>(badge.shadowRoot!, 'button'));
  await sendKeys({ press: 'Enter' });
  expect(selected).to.deep.equal(['report']);
  sources.delete('report'); app.refreshSources();
  await ready(app);
  expect(view.shadowRoot!.querySelector('lr-citation-badge') === null).to.equal(true);
  expect(view.shadowRoot!.textContent).to.contain('Source unavailable');
  app.transcript.dispatchEvent(new CustomEvent('lr-citation-activate', { bubbles: true, composed: true, detail: { sourceId: 'report' } }));
  expect(selected).to.deep.equal(['report']);
});

it('sends one host next-turn request from keyboard suggestion activation and disables chips while it is pending', async () => {
  const questions: string[] = [];
  let complete!: () => void;
  const { app } = await mount({ onAsk: request => {
    questions.push(request.question); return new Promise<void>(resolve => { complete = resolve; });
  } });
  app.push(formIsland); app.finish();
  await ready(app); await app.suggestions.updateComplete;
  const button = query<HTMLButtonElement>(app.suggestions.shadowRoot!, 'button');
  await focusByKeyboard(button); await sendKeys({ press: 'Enter' });
  await app.suggestions.updateComplete;
  expect(questions).to.deep.equal(['Explain the answer in more detail.']);
  expect(query<HTMLButtonElement>(app.suggestions.shadowRoot!, 'button').disabled).to.equal(true);
  await sendKeys({ press: 'Enter' });
  expect(questions.length).to.equal(1);
  complete();
  await waitUntil(() => !app.controller.asking);
});

it('moves the same generated surface to an artifact panel and back with edited state and a valid focus target', async () => {
  const { app } = await mount();
  app.push(formIsland); app.finish();
  const view = await ready(app);
  const input = nativeInput(view);
  await focusByKeyboard(input); await sendKeys({ type: 'Preserve panel state' });
  const ownedShell = shell(view);
  const partId = app.controller.snapshot.islands[0]!.partId;
  // Exercise the insertBefore fallback used by browsers without state-preserving moveBefore.
  Object.defineProperty(app.panel, 'moveBefore', { configurable: true, value: undefined });
  app.openInPanel(partId);
  await app.transcript.updateComplete; await app.panel.updateComplete;
  expect(ownedShell.parentElement === app.panel).to.equal(true);
  expect(query(app.panel, 'lr-gen-view') === view).to.equal(true);
  expect(activeElement() === input).to.equal(true);
  expect(input.value).to.equal('Preserve panel state');
  expect(ownedShell.textContent).to.contain('Generated by the assistant');
  expect(app.transcript.shadowRoot!.textContent).to.contain('Generated content is in the panel');
  app.returnToTranscript(partId);
  await app.transcript.updateComplete; await twoFrames();
  expect(query(app.transcript.shadowRoot!, 'lr-gen-view') === view).to.equal(true);
  expect(nativeInput(view) === input).to.equal(true);
  expect(input.value).to.equal('Preserve panel state');
  expect(activeElement()?.isConnected).to.equal(true);
  expect(activeElement() === ownedShell || activeElement() === input).to.equal(true);
  // An idempotent movement must preserve its current focus too.
  moveChatSurface(ownedShell, ownedShell.parentElement!, ownedShell.nextSibling);
  expect(activeElement()?.isConnected).to.equal(true);
});
