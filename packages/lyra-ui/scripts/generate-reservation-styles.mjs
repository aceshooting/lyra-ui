#!/usr/bin/env node
// Generates src/styles/reservations.styles.ts -- the adoptable (CSSResult) form of
// src/styles/reservations.css -- from that same CSS source, so the two can never drift the way a
// hand-copied second version would. reservations.css is a light-DOM stylesheet: importing it at
// document scope cannot reach an lr-* element that a consumer's OWN component renders inside its
// OWN shadow root, because a document stylesheet never crosses a shadow boundary. The generated
// module is the fix: `static styles = [reservationStyles, ...]` (or
// `shadowRoot.adoptedStyleSheets = [reservationStyles.styleSheet]`) adopts the identical rules
// directly into that shadow root.
//
// Also runnable directly: `node scripts/generate-reservation-styles.mjs` (or
// `pnpm run generate-reservation-styles`) from `packages/lyra-ui/`.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMainModule } from './is-main-module.mjs';

const packageDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const cssPath = path.join(packageDir, 'src', 'styles', 'reservations.css');
const outputPath = path.join(packageDir, 'src', 'styles', 'reservations.styles.ts');

/**
 * Strips every `/* ... *\/` block comment from a standalone CSS file, then collapses the runs of
 * blank lines the removal leaves behind. reservations.css's own header prose quotes selectors and
 * custom properties in backticks (`` `lr-chart` ``); embedding that prose verbatim inside a `css`
 * tagged template would terminate the JS template literal early, so the generated module keeps
 * its own JSDoc instead and carries only the executable rules.
 */
export function stripCssComments(source) {
  const lines = source
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .map((line) => line.replace(/[ \t]+$/, ''));
  const collapsed = lines.filter((line, index, all) => {
    if (line !== '') return true;
    const previous = all[index - 1];
    return previous !== undefined && previous !== '' && !previous.trimEnd().endsWith('{');
  });
  return collapsed.join('\n').replace(/^\n+/, '').replace(/\n+$/, '');
}

export function buildReservationStylesModule(packageDir_ = packageDir) {
  const css = readFileSync(path.join(packageDir_, 'src', 'styles', 'reservations.css'), 'utf8');
  const stylesheet = stripCssComments(css);
  if (stylesheet.includes('`') || stylesheet.includes('${')) {
    throw new Error(
      'reservations.css: a backtick or ${ survived comment stripping and would break the ' +
        'generated `css` tagged template; update generate-reservation-styles.mjs before rerunning.',
    );
  }
  const indented = stylesheet
    .split('\n')
    .map((line) => (line.length ? `  ${line}` : line))
    .join('\n');
  return `// GENERATED by scripts/generate-reservation-styles.mjs from src/styles/reservations.css --
// do not edit this file; edit reservations.css and regenerate instead.
import { css, type CSSResult } from 'lit';

/**
 * Adoptable ('CSSResult') form of the layout-shift reservations in 'reservations.css'.
 *
 * 'reservations.css' is a light-DOM stylesheet: '@import'-ing it at document scope reserves
 * layout only for 'lr-*' usages that live in that same light DOM. It cannot reach an 'lr-*'
 * element that a consumer's OWN component renders inside its OWN shadow root, because a document
 * stylesheet never crosses a shadow boundary. Adopt this export directly into that shadow root
 * instead, so the same rules -- the same custom properties and fallback tokens the owning
 * component's own stylesheet reads -- apply there too:
 *
 * \`\`\`ts
 * static styles = [reservationStyles, css\`...\`];
 * // or, outside a LitElement:
 * shadowRoot.adoptedStyleSheets = [reservationStyles.styleSheet!];
 * \`\`\`
 */
export const reservationStyles: CSSResult = css\`
${indented}
\`;
`;
}

if (isMainModule(import.meta.url)) {
  const check = process.argv.includes('--check');
  const content = buildReservationStylesModule();
  if (check) {
    const current = existsSyncSafe(outputPath) ? readFileSync(outputPath, 'utf8') : null;
    if (current !== content) {
      console.error(`Stale: ${path.relative(packageDir, outputPath)} does not match reservations.css.`);
      process.exitCode = 1;
    } else {
      console.log('reservations.styles.ts is fresh.');
    }
  } else {
    writeFileSync(outputPath, content);
    console.log(`Wrote ${path.relative(packageDir, outputPath)}.`);
  }
}

function existsSyncSafe(file) {
  try {
    readFileSync(file, 'utf8');
    return true;
  } catch {
    return false;
  }
}
