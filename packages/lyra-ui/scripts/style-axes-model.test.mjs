test('reference surfaces accept one value or sparse mode pairs', () => {
  const model = readStyleModel(packageDir);
  model.looks = [
    { id: 'plain', tokens: { '--lr-theme-color-surface-default': '#eeeeee' } },
    { id: 'sparse', tokens: { '--lr-theme-color-surface-default': { dark: '#111111' } } },
  ];
  const references = referenceSurfaces(model);
  assert.deepEqual(references.plain, { light: '#eeeeee', dark: '#eeeeee' });
  assert.deepEqual(references.sparse, { light: model.base['--lr-theme-color-surface-default'].light, dark: '#111111' });
});

test('clear media scrim plus fill qualifies white controls over black and white', () => {
  const { clearMedia } = JSON.parse(readFileSync(new URL('../tokens/surfaces/glass.json', import.meta.url), 'utf8'));
  const luminance = channel => channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
  for (const backdrop of [0, 1]) for (const scrim of [clearMedia.scrimStart, clearMedia.scrimEnd]) {
    const painted = (clearMedia.fillOpacity + backdrop * (1 - clearMedia.fillOpacity)) * (1 - scrim);
    for (const hover of [0, clearMedia.fillOpacity]) {
      const background = painted * (1 - hover) + hover;
      assert.ok(1.05 / (luminance(background) + 0.05) >= 4.5, 'white text and controls preserve their contrast through hover and press');
    }
  }
});
