import { readStyleModel, renderFixedLook, renderRuntimeLook, renderTheme, concreteThemeCss, referenceSurfaces, renderAccents, contrastSurfaces, validateLook, renderGlass } from './style-axes-model.mjs';

const packageDir = dirname(dirname(fileURLToPath(import.meta.url)));

test('concrete theme extraction retains both generated mode slots and shared inputs', () => {
  const model = readStyleModel(packageDir);
  const css = concreteThemeCss(renderTheme(model));
  const [light, dark] = css.split('  .lr-dark,');
  assert.ok(dark, 'a dark projection is present independently of resolver selector syntax');
  for (const [name, values] of Object.entries(model.base)) {
    assert.ok(light.includes(`${name}: ${values.light};`), `${name}: concrete light value`);
    if (values.dark !== undefined) {
      assert.ok(dark.includes(`${name}: ${values.dark};`), `${name}: concrete dark value`);
    } else {
      assert.equal(dark.includes(`${name}:`), false, `${name}: no invented dark override`);
    }
  }
  assert.equal(css.includes('--_lr-'), false);
  for (const name of model.names.filter(name => !model.base[name])) {
    assert.equal(light.includes(`${name}: initial;`), false, 'absent optional look inputs stay undeclared');
  }
});

test('concrete theme preserves explicitly authored optional initial inputs without inventing look defaults', () => {
  const model = readStyleModel(packageDir);
  model.base['--lr-theme-line-break'] = { light: 'initial' };
  const generated = renderTheme(model);
  const projected = concreteThemeCss(generated);
  assert.match(projected, /--lr-theme-line-break: initial;/);
  assert.doesNotMatch(projected, /--lr-theme-font-family-heading: initial;/);
  assert.throws(() => concreteThemeCss(generated.replace(
    '--lr-theme-line-break: initial; /* declared optional input */',
    '--lr-theme-line-break: normal; /* declared optional input */',
  )), /Invalid declared optional input/);
  model.slotted.push('--lr-theme-line-break');
  model.paired.push('--lr-theme-line-break');
  const [light, dark] = concreteThemeCss(renderTheme(model)).split('  .lr-dark,');
  assert.match(light, /--lr-theme-line-break: initial;/);
  assert.doesNotMatch(dark, /--lr-theme-line-break:/);
});

test('concrete theme extraction fails closed for missing generated rules and dark slots', () => {
  const header = '/* GENERATED by scripts/generate-style-axes.mjs; */\n';
  assert.throws(() => concreteThemeCss(header), /no base input rule/);
  assert.throws(() => concreteThemeCss(`${header}:root, [data-lr-look] { --lr-theme-color-focus: #123456; }`), /no dark input slots/);
  const legacy = ':root { --lr-theme-color-focus: #123456; }';
  assert.equal(concreteThemeCss(legacy), legacy);
  const generated = renderTheme(readStyleModel(packageDir));
  const wrongFallback = generated.replace(/(--_lr-ld-[a-z0-9-]+):[^;]+; \/\* mode-independent fallback \*\//, '$1: 999px; /* mode-independent fallback */');
  assert.notEqual(wrongFallback, generated);
  assert.throws(() => concreteThemeCss(wrongFallback), /fallback differs from light input/);
});

