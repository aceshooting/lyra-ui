// Which shipped catalog messages the published translations package may omit because the runtime
// already resolves them to the identical English default.
//
// A message can only be dropped when the lookup chain of its locale falls straight from that
// locale's own catalog to the built-in English default. That holds for a catalog that declares no
// parent locale and shares its base language with no other standalone shipped catalog: a regional
// sibling (`pt-BR`/`pt-PT`, `zh-CN`/`zh-TW`, `fa`/`fa-AF`) or a truncation step (`sr`/`sr-Latn`)
// would otherwise answer the omitted key with its own, possibly different, text. Delta catalogs
// (`de-CH`, `fr-CA`) inherit from such a parent, so they reach English exactly when the parent
// would have answered with English, and need no entry of their own.
//
// Authored sources stay complete; `check-translations.mjs` and the catalog inventory keep reading
// whole catalogs. The generated list is the build input of the trim and the development-only
// record that keeps the missing-message diagnostic quiet for these keys.

import { parseProgram } from './lib/ast.mjs';

const literal = (node) => {
  if (node?.type === 'Literal' && typeof node.value === 'string') return node.value;
  if (node?.type === 'TemplateLiteral' && node.expressions.length === 0) return node.quasis[0].value.cooked;
  throw new Error('a catalog message must be a string literal or a flat plural record');
};

/** One authored message literal (a string or a flat plural record) as order-insensitive JSON. */
function messageValue(text) {
  const program = parseProgram('message.ts', `(${text});`);
  let node = program.body[0]?.expression;
  while (node?.type === 'ParenthesizedExpression') node = node.expression;
  if (node?.type !== 'ObjectExpression') return JSON.stringify(literal(node));
  return JSON.stringify(node.properties
    .map((property) => [property.key.name ?? property.key.value, literal(property.value)])
    .sort(([a], [b]) => (a < b ? -1 : 1)));
}

/**
 * @param {Map<string, { parent?: string | null, entries: Map<string, string> }>} catalogs
 *   Shipped locale tag -> its parent tag and its own authored entries (raw literal source).
 * @param {Map<string, string>} english DEFAULT_STRINGS key -> raw literal source.
 * @returns {Map<string, string[]>} Locale tag -> omitted keys in English catalog order, for every
 *   qualifying locale with at least one English-identical message.
 */
export function englishDefaultLocaleKeys(catalogs, english) {
  const standalone = [...catalogs].filter(([, catalog]) => !catalog.parent).map(([tag]) => tag);
  const base = (tag) => tag.split('-')[0].toLowerCase();
  const englishValues = new Map([...english].map(([key, text]) => [key, messageValue(text)]));
  const result = new Map();
  for (const tag of [...standalone].sort()) {
    if (standalone.filter((other) => base(other) === base(tag)).length !== 1) continue;
    const entries = catalogs.get(tag).entries;
    const keys = [...englishValues]
      .filter(([key, value]) => entries.has(key) && messageValue(entries.get(key)) === value)
      .map(([key]) => key);
    if (keys.length > 0) result.set(tag, keys);
  }
  return result;
}

/** The generated development-only module carrying {@link englishDefaultLocaleKeys}. */
export function englishDefaultsModuleSource(localeKeys) {
  const lines = [...localeKeys].map(([tag, keys]) => `  '${tag.toLowerCase()}': '${keys.join(' ')}',`);
  return `// GENERATED by scripts/generate-translation-slices.mjs -- do not edit by hand.
// Messages the published locale catalogs omit because they equal the English default and their
// locale falls straight back to it (see scripts/locale-english-defaults.mjs). Read only by the
// development diagnostics, so the missing-message warning stays quiet for them.

export const LOCALE_ENGLISH_DEFAULT_KEYS: Readonly<Record<string, string>> = {
${lines.join('\n')}
};
`;
}
