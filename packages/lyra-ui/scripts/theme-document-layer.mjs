// theme.css carries the document token layer (RFC 0002) after the style model's own rules,
// byte-identical to the body of tokens-root.css and to the constructed copy the runtime adopts.
// Applications import theme.css before any component connects, so the layer applies from the first
// style pass: the runtime finds its sentinel, adopts no constructed copy, and no first connect has
// to invalidate a large existing document.
import { buildDocumentLayerCss } from './document-token-layer.mjs';
import { projectDefaultTokenSource, readCanonicalTokens } from './generate-design-tokens.mjs';
import { renderTheme } from './style-axes-model.mjs';
import { rootResolvedReferenceViolations } from './theme-boundary-lint.mjs';

const ORDER = '@layer lr-base, lr-theme, lr-theme-preset, lr-utilities, lr-overrides;';
const THEME_LAYER_MARKER = '/* The document token layer (RFC 0002), identical to tokens-root.css; generated by scripts/document-token-layer.mjs. */';

/** The layer text theme.css appends: the tokens-root.css body without its repeated order statement. */
function themeDocumentLayer(packageDir) {
  const layer = buildDocumentLayerCss(projectDefaultTokenSource(readCanonicalTokens(packageDir), packageDir), ORDER);
  if (!layer.startsWith(`${ORDER}\n`)) throw new Error('Document token layer prelude changed');
  return `${THEME_LAYER_MARKER}\n${layer.slice(ORDER.length + 1)}`;
}

/** The complete generated theme.css. */
export function renderThemeCss(model) {
  const css = renderTheme(model);
  if (!css.includes(`\n${ORDER}\n`) && !css.includes(`*/\n${ORDER}\n`)) throw new Error('theme.css no longer opens with the Lyra layer order statement');
  const full = `${css}${themeDocumentLayer(model.packageDir)}`;
  const frozen = rootResolvedReferenceViolations(full);
  if (frozen.length) throw new Error(`theme.css freezes a re-declared name at :root:\n- ${frozen.join('\n- ')}`);
  return full;
}
