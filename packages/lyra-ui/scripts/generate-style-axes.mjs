import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderThemeCss } from './theme-document-layer.mjs';
import { readStyleModel, renderLook, renderDensity, renderGlass, renderAccents, renderRuntimeLook, referenceSurfaces, contrastSurfaces, modeResolverDeclarations, defaultStyleInputs, replaceStyleFallbacks, quote, STYLE_VERSION } from './style-axes-model.mjs';

const packageDir = dirname(dirname(fileURLToPath(import.meta.url)));
const model = readStyleModel(packageDir);
const outputs = new Map();
outputs.set('src/theme.css', renderThemeCss(model));
const profileInputs = defaultStyleInputs(model);
const tokenPath = 'src/internal/tokens.styles.ts';
const glassData = JSON.parse(readFileSync(join(packageDir, 'tokens/surfaces/glass.json'), 'utf8'));
const tokenTemplate = readFileSync(join(packageDir, tokenPath), 'utf8');
const glassPattern = /(\/\* glass defaults: generated \*\/\n)[\s\S]*?(    \/\* glass defaults: end \*\/)/;
if (!glassPattern.test(tokenTemplate)) throw new Error('Intrinsic glass default markers changed');
const glassDefaults = `    --_lr-surface-default-blur: ${glassData.blur};
    --_lr-surface-default-maximum-blur: ${glassData.maximumBlur};
    --_lr-surface-default-highlight: ${glassData.highlight};
    --_lr-glass-dark-anchor: ${glassData.darkFillAnchor};
`;
const tokenSource = tokenTemplate.replace(glassPattern, `$1${glassDefaults}$2`);
const darkMarker = tokenSource.indexOf('/* @media (prefers-color-scheme: dark) */');
const auxiliaryMarker = tokenSource.indexOf('const auxTokens');
if (darkMarker < 0 || auxiliaryMarker < darkMarker) throw new Error('Token fallback mode markers changed');
outputs.set(tokenPath, replaceStyleFallbacks(tokenSource.slice(0, darkMarker), profileInputs, 'light', model.canonical.tokens) + replaceStyleFallbacks(tokenSource.slice(darkMarker, auxiliaryMarker), profileInputs, 'dark', model.canonical.tokens) + tokenSource.slice(auxiliaryMarker));
const sizesPath = 'src/internal/sizes.styles.ts';
outputs.set(sizesPath, replaceStyleFallbacks(readFileSync(join(packageDir, sizesPath), 'utf8'), profileInputs, 'light', model.canonical.tokens));
const specialistPath = 'src/internal/specialist-tokens.styles.ts';
const specialistSource = readFileSync(join(packageDir, specialistPath), 'utf8');
const specialistDark = specialistSource.indexOf('const darkSpecialistTokens');
const specialistForced = specialistSource.indexOf('const forcedColorSpecialistTokens');
if (specialistDark < 0 || specialistForced < specialistDark) throw new Error('Specialist fallback mode markers changed');
outputs.set(specialistPath, replaceStyleFallbacks(specialistSource.slice(0, specialistDark), profileInputs, 'light', model.canonical.tokens) + replaceStyleFallbacks(specialistSource.slice(specialistDark, specialistForced), profileInputs, 'dark', model.canonical.tokens) + specialistSource.slice(specialistForced));


outputs.set('src/density.css', renderDensity(JSON.parse(readFileSync(join(packageDir, 'tokens/density.json'), 'utf8'))));
outputs.set('src/surfaces/glass.css', renderGlass(JSON.parse(readFileSync(join(packageDir, 'tokens/surfaces/glass.json'), 'utf8'))));
for (const look of model.looks) {
  outputs.set(`src/looks/${look.id}.css`, renderLook(model, look, { modeAliases: look.id === 'shadcn' }));
  outputs.set(`src/theme/looks/${look.id}.ts`, renderRuntimeLook(look));
}
// The gemstone data module remains the canonical palette; runtime literals keep theme.js free of imports.
const gemstoneSource = readFileSync(join(packageDir, 'src/theme/gemstones-data.ts'), 'utf8');
const gemstones = Object.fromEntries([...gemstoneSource.matchAll(/(\w+): \{ key: '\w+', fill: '([^']+)'/g)].map(match => [match[1], match[2]]));
outputs.set('src/accents.css', renderAccents(model, gemstones));
if (Object.keys(gemstones).length !== 9) throw new Error('Gemstone data shape changed; update the style model reader');
const references = referenceSurfaces(model, true);
const contrastReferences = contrastSurfaces(model);
const array = values => `[\n${values.map(value => `  ${quote(value)},`).join('\n')}\n]`;
outputs.set('src/theme/look-inputs.ts', `// GENERATED by scripts/generate-style-axes.mjs.
export const LOOK_STYLE_VERSION = ${quote(STYLE_VERSION)};
export const LOOK_SLOTTED_INPUTS: readonly string[] = ${array(model.slotted)};
export const LOOK_MODE_RESOLVER = ${quote(modeResolverDeclarations(model).map(([name, value]) => `    ${name}: ${value};`).join('\n'))};
`);
const branch = value => Array.isArray(value) ? `[${value.map(quote).join(', ')}]` : quote(value);
const object = values => `{\n${Object.entries(values).map(([key, value]) => `  ${quote(key)}: ${typeof value === 'string' ? quote(value) : `{ light: ${branch(value.light)}, dark: ${branch(value.dark)} }`},`).join('\n')}\n}`;
const generated = `// GENERATED STYLE MODEL: START\nconst STYLE_DEFAULTS = Object.freeze(${object(model.defaults)} as const);\nconst STYLE_SLOTTED: readonly string[] = ${array(model.slotted)};\nconst STYLE_DENSITY: readonly string[] = ${array(model.density)};\nconst STYLE_FOLLOW: readonly string[] = ${array(model.follow)};\nconst STYLE_REFERENCE_SURFACES: Readonly<Record<string, { light: readonly string[]; dark: readonly string[] }>> = ${object(references)};\nconst STYLE_CONTRAST_SURFACES: Readonly<Record<'light' | 'dark', readonly string[]>> = {\n  light: ${array(contrastReferences.light)},\n  dark: ${array(contrastReferences.dark)},\n};\nconst STYLE_GEMSTONES: Readonly<Record<string, string>> = ${object(gemstones)};\n// GENERATED STYLE MODEL: END`;
const runtimePath = 'src/theme/theme.ts';
const runtime = readFileSync(join(packageDir, runtimePath), 'utf8');
if (!runtime.includes('// GENERATED STYLE MODEL: START')) throw new Error('Style model marker missing');
outputs.set(runtimePath, runtime.replace(/\/\/ GENERATED STYLE MODEL: START[\s\S]*?\/\/ GENERATED STYLE MODEL: END/, () => generated));
let stale = false;
for (const [relative, content] of outputs) {
  const path = join(packageDir, relative);
  let current;
  try { current = readFileSync(path, 'utf8'); } catch { current = null; }
  if (current === content) continue;
  if (process.argv.includes('--check')) { console.error(`Stale generated style asset: ${relative}`); stale = true; }
  else { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, content); console.log(relative); }
}
if (stale) process.exitCode = 1;
