import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMainModule } from './is-main-module.mjs';
import { quote, readStyleModel, validateLook } from './style-axes-model.mjs';

const defaultPackageDir = dirname(dirname(fileURLToPath(import.meta.url)));
const KINDS = Object.freeze(['shape', 'typography', 'elevation']);
const INPUTS = Object.freeze({
  shape: /^--lr-theme-(?:border-radius-(?:xs|m|button|container)|form-control-radius)$/,
  typography: /^--lr-theme-(?:font-family-(?:body|heading|mono)|font-size-(?:3xs|2xs|xs|sm|m|md-sm|lg|xl|2xl|3xl)|line-height-(?:compact|snug|normal|loose)|line-break|word-break)$/,
  elevation: /^--lr-theme-(?:shadow-(?:xs|s|m|l|xl|color)|color-surface-container(?:-lowest|-low|-high|-highest)?|color-text-quiet)$/,
});

/** Structural schema plus the shared look grammar and runtime mode-slot contract. */
export function validateOptionPresetSource(source, slottedInputs) {
  if (!source || typeof source !== 'object' || Array.isArray(source) ||
      Object.keys(source).some(key => !['$schema', 'schemaVersion', 'kind', 'presets'].includes(key)) ||
      source.schemaVersion !== 1 || !KINDS.includes(source.kind) ||
      (source.$schema !== undefined && typeof source.$schema !== 'string')) {
    throw new Error('Invalid optional preset source');
  }
  if (!source.presets || typeof source.presets !== 'object' || Array.isArray(source.presets)) throw new Error(`${source.kind}: invalid presets`);
  const entries = Object.entries(source.presets);
  if (!entries.length || entries.length > 16) throw new Error(`${source.kind}: presets must contain 1–16 entries`);
  const slotted = new Set(slottedInputs);
  for (const [id, tokens] of entries) {
    validateLook({ id, tokens });
    if (!Object.keys(tokens).length) throw new Error(`${source.kind}/${id}: empty preset`);
    for (const [name, value] of Object.entries(tokens)) {
      if (!INPUTS[source.kind].test(name)) throw new Error(`${source.kind}/${id}: input belongs to another option: ${name}`);
      if (typeof value !== 'string' && !slotted.has(name)) throw new Error(`${source.kind}/${id}: per-mode input has no runtime resolver: ${name}`);
    }
  }
}

export function readOptionPresetSources(packageDir = defaultPackageDir) {
  const directory = join(packageDir, 'tokens', 'options');
  const { slotted } = readStyleModel(packageDir);
  const sources = readdirSync(directory).filter(file => file.endsWith('.json')).sort().map(file => {
    const source = JSON.parse(readFileSync(join(directory, file), 'utf8'));
    validateOptionPresetSource(source, slotted);
    if (`${source.kind}.json` !== file) throw new Error(`Optional preset kind must match its filename: tokens/options/${file}`);
    return source;
  });
  if (sources.length !== KINDS.length || KINDS.some(kind => !sources.some(source => source.kind === kind))) {
    throw new Error(`Optional preset sources must contain ${KINDS.join(', ')}`);
  }
  return sources;
}

const orderedPresets = source => Object.fromEntries(Object.entries(source.presets)
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([id, tokens]) => [id, Object.fromEntries(Object.entries(tokens)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, value]) => [name, typeof value === 'string' ? value : Object.fromEntries(
      ['light', 'dark'].filter(mode => Object.hasOwn(value, mode)).map(mode => [mode, value[mode]]),
    )]))]));

export function buildOptionPresetInterchange(sources) {
  return {
    schemaVersion: 1,
    presets: Object.fromEntries([...sources].sort((left, right) => left.kind.localeCompare(right.kind))
      .map(source => [source.kind, orderedPresets(source)])),
  };
}

export function renderOptionPresetModule(source) {
  const name = `LYRA_${source.kind.toUpperCase()}_PRESETS`;
  const type = `Lyra${source.kind[0].toUpperCase()}${source.kind.slice(1)}PresetName`;
  const entries = Object.entries(orderedPresets(source)).map(([id, tokens]) => {
    const declarations = Object.entries(tokens).map(([token, value]) => {
      const expression = typeof value === 'string' ? quote(value) : `Object.freeze({ ${Object.entries(value).map(([mode, branch]) => `${mode}: ${quote(branch)}`).join(', ')} })`;
      return `    ${quote(token)}: ${expression},`;
    });
    return `  ${quote(id)}: Object.freeze({\n${declarations.join('\n')}\n  }),`;
  });
  return `// GENERATED by scripts/generate-option-presets.mjs; edit tokens/options/${source.kind}.json.\n` +
    `import type { LyraThemeTokens } from '../theme.js';\n\n` +
    `/** Optional ${source.kind} token maps. Compose selected maps through style overrides. */\n` +
    `export const ${name} = Object.freeze({\n${entries.join('\n')}\n}) satisfies Readonly<Record<string, LyraThemeTokens>>;\n\n` +
    `export type ${type} = keyof typeof ${name};\n`;
}

export function generateOptionPresets({ packageDir = defaultPackageDir, check = false } = {}) {
  const sources = readOptionPresetSources(packageDir);
  const stale = [];
  for (const source of sources) {
    const file = join(packageDir, 'src', 'theme', 'options', `${source.kind}.ts`);
    const expected = renderOptionPresetModule(source);
    if (check) {
      if (!existsSync(file) || readFileSync(file, 'utf8') !== expected) stale.push(source.kind);
    } else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, expected);
    }
  }
  if (stale.length) throw new Error(`Stale generated optional presets: ${stale.join(', ')}`);
}

if (isMainModule(import.meta.url)) {
  const check = process.argv.includes('--check');
  generateOptionPresets({ check });
  console.log(`Optional shape, typography and elevation presets ${check ? 'are current' : 'generated'}.`);
}
