/**
 * Resolve a message through the public full-catalog entry. Component classes use the lean runtime
 * directly with their generated per-class defaults, keeping this complete compatibility catalog
 * out of granular component bundles.
 */
export function resolveLyraString(
  host: Element,
  key: string,
  overrides?: LyraLocaleStrings,
  fallback?: string,
  values?: Record<string, string | number>
): string {
  return resolveRuntimeLyraString(
    host,
    key,
    overrides,
    fallback,
    values,
    DEFAULT_STRINGS
  );
}

