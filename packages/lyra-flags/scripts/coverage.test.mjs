import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import test from 'node:test';
import { sourceInventory } from '../../lyra-docs/scripts/lib/node-coverage.mjs';
import { stageScripts } from '../../lyra-docs/scripts/lib/staged-script.mjs';
import { GENERATED_BANNER, ROOT, SCOPE } from './coverage.mjs';

const generatedRule = SCOPE.exclude.find(rule => rule.verify);

test('every JavaScript file of the package is either measured or excluded for a stated reason', async () => {
  const { included, excluded } = await sourceInventory({ root: ROOT, include: SCOPE.include, exclude: SCOPE.exclude });
  assert.deepEqual(included.map(entry => entry.name), [...SCOPE.include].sort());
  const generated = excluded.find(({ reason }) => reason === generatedRule.reason);
  assert.ok(generated.count > 249, 'one loader per flag plus the maps are excluded as generated');
  assert.deepEqual(excluded.map(({ reason }) => reason).sort(), ['generated by scripts/generate-index.mjs', 'test']);
});

test('the exclusion applies to the generated tree and to nothing else', () => {
  const generatedPaths = ['flags/generated.js', 'flags/eager.js', 'flags/loaders/fr.js', 'flags/detailed/loaders/es.js', 'flags/compact/loaders/es.js'];
  for (const path of generatedPaths) assert.equal(generatedRule.pattern.test(path), true, path);
  for (const path of ['index.js', 'standard.js', 'scripts/generate-index.mjs', 'scripts/flags/x.js', 'flags.js', 'flags/fr.svg', 'flags/generated.d.ts']) {
    assert.equal(generatedRule.pattern.test(path), false, path);
  }
});

test('the banner the exclusion demands is the banner the committed generated files carry', () => {
  for (const file of ['flags/generated.js', 'flags/eager.js', 'flags/generated-detailed.js', 'flags/generated-compact.js', 'flags/loaders/fr.js']) {
    assert.equal(readFileSync(join(ROOT, file), 'utf8').startsWith(GENERATED_BANNER), true, file);
  }
});

test('hand-written code in the generated tree is refused instead of being excluded', async () => {
  assert.doesNotThrow(() => generatedRule.verify('flags/loaders/fr.js', `${GENERATED_BANNER}export default 1;\n`));
  assert.throws(() => generatedRule.verify('flags/loaders/fr.js', 'export default 1;\n'),
    /flags\/loaders\/fr\.js sits in the generated tree without the generator banner/u);

  const root = mkdtempSync(join(tmpdir(), 'lyra-flags-scope-'));
  try {
    for (const [file, text] of Object.entries({ 'index.js': 'export {};\n', 'flags/hand-written.js': 'export {};\n' })) {
      mkdirSync(dirname(join(root, file)), { recursive: true });
      writeFileSync(join(root, file), text);
    }
    await assert.rejects(sourceInventory({ root, include: ['index.js'], exclude: SCOPE.exclude }),
      /flags\/hand-written\.js sits in the generated tree without the generator banner/u);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test('a script nobody classified would stop the measurement', async () => {
  await assert.rejects(sourceInventory({ root: ROOT, include: SCOPE.include.filter(name => name !== 'scripts/optimize-flags.mjs'), exclude: SCOPE.exclude }),
    /Unclassified JavaScript source: scripts\/optimize-flags\.mjs/u);
});

test('the floor is a percentage the package can meet', () => {
  assert.ok(Number.isFinite(SCOPE.floor) && SCOPE.floor > 0 && SCOPE.floor <= 100);
});

/** The runner staged beside the real measurement engine, with a package whose own test covers little. */
function stagedRunner(context) {
  const root = mkdtempSync(join(tmpdir(), 'lyra-flags-runner-'));
  context.after(() => rmSync(root, { recursive: true, force: true }));
  const own = join(root, 'packages', 'lyra-flags');
  mkdirSync(join(root, 'packages'));
  symlinkSync(join(ROOT, '..', 'lyra-docs'), join(root, 'packages', 'lyra-docs'), 'junction');
  const staged = stageScripts({ from: ROOT, to: own, files: SCOPE.include });
  writeFileSync(join(own, 'package.json'), JSON.stringify({ name: 'fixture', scripts: { test: 'node --test scripts/partial.test.mjs' } }));
  writeFileSync(join(own, 'scripts/partial.test.mjs'),
    `import assert from 'node:assert/strict';\nimport { readFileSync } from 'node:fs';\nimport { join } from 'node:path';\nimport test from 'node:test';\nimport { packageDir, put } from './test-support.mjs';\ntest('writes nested files', () => {\n  put(join(packageDir, 'coverage', 'tmp-probe', 'a', 'b.txt'), 'probe');\n  assert.equal(readFileSync(join(packageDir, 'coverage', 'tmp-probe', 'a', 'b.txt'), 'utf8'), 'probe');\n});\n`);
  return { own, run: () => spawnSync(process.execPath, [staged[SCOPE.include.indexOf('scripts/coverage.mjs')]], { encoding: 'utf8' }) };
}

test('the command line measures its own package and fails the run when the floor is missed', context => {
  const { own, run } = stagedRunner(context);
  const result = run();
  assert.equal(result.status, 1, result.stderr);
  assert.match(result.stdout, /@aceshooting\/lyra-flags coverage - lines \d+(?:\.\d+)?% \(\d+\/\d+\)/u);
  assert.match(result.stderr, new RegExp(`lines coverage \\d+\\.\\d{3}% is below ${SCOPE.floor}%`, 'u'));
  const metadata = JSON.parse(readFileSync(join(own, 'coverage/coverage-metadata.json'), 'utf8'));
  assert.equal(metadata.package, '@aceshooting/lyra-flags');
  assert.equal(metadata.complete, true);
  assert.deepEqual(metadata.included, [...SCOPE.include].sort());
  assert.deepEqual(metadata.unloaded, [...SCOPE.include].sort().filter(name => name !== 'scripts/test-support.mjs'));
});
