test('delegated state and action ownership follows the original emitter across message-parts shadow roots', () => {
  const middle = { document: { surfaceId: 'retained-surface-25:island-0' } };
  const other = { document: { surfaceId: 'retained-surface-20:island-0' } }, body = {};
  const views = [middle, other];
  for (const type of ['lr-gen-state-change', 'lr-gen-action']) {
    const event = { type, target: body, detail: { surfaceId: middle.document.surfaceId }, composedPath: () => [middle, body] };
    assert.equal(memoryChatEventView(event, views), middle);
    assert.equal(memoryChatEventView({ ...event, composedPath: () => [other, body] }, views), undefined);
    assert.equal(memoryChatEventView({ ...event, target: middle, composedPath: () => [{}, middle, body] }, views), undefined);
    assert.equal(memoryChatEventView({ ...event, detail: { surfaceId: other.document.surfaceId } }, views), undefined);
    assert.equal(memoryChatEventView(event, [other]), undefined);
  }
});

test('action origin requires an existing middle view and a resolved owned emitter', () => {
  const middle = { document: { surfaceId: 'retained-surface-25:island-0' } };
  const other = { document: { surfaceId: 'retained-surface-20:island-0' } };
  const event = { detail: { surfaceId: middle.document.surfaceId }, composedPath: () => [middle] };
  validateMemoryChatActionOrigin(event, [middle], middle);
  assert.throws(() => validateMemoryChatActionOrigin(event, [], undefined), /Foreign chat action/u);
  assert.throws(() => validateMemoryChatActionOrigin(event, [middle], undefined), /Foreign chat action/u);
  assert.throws(() => validateMemoryChatActionOrigin(event, [], middle), /Foreign chat action/u);
  assert.throws(() => validateMemoryChatActionOrigin({ ...event, composedPath: () => [other] }, [middle, other], middle), /Foreign chat action/u);
});

test('factory is inert and closing a pending import removes all work without a late mount', async () => {
  let imports = 0, resolve, appends = 0;
  const loading = new Promise(done => { resolve = done; });
  const host = { childNodes: [], append() { appends++; }, replaceChildren() { this.childNodes = []; } };
  const app = await createMemoryApplication({ host, services, cycle: 1, signal: new AbortController().signal, load: () => { imports++; return loading; } });
  assert.equal(imports, 0); assert.deepEqual(app.metrics(), { sourceCharacters: 0, controllerParts: 0, controllerIslands: 0, pendingOperations: 0, actions: 0 });
  const mounted = app.mount(); await Promise.resolve(); assert.equal(imports, 1);
  await app.close(); await assert.rejects(mounted, /aborted/u);
  resolve({}); await Promise.resolve();
  assert.equal(appends, 0); assert.equal(app.metrics().pendingOperations, 0); await app.close();
});

test('unmounted lifecycle cannot save, release or restore fabricated ownership', async () => {
  const app = await createMemoryApplication({ host: { childNodes: [], replaceChildren() {} }, services, cycle: 1 });
  assert.throws(() => app.save()); assert.throws(() => app.releaseSources());
  await assert.rejects(app.restore({}), /first disposed/u);
  await app.close();
});
