const form = (index, cycle) => ({ id: `form-${index}`, type: 'stack', children: [
  { id: `heading-${index}`, type: 'heading', text: `Review answer ${index}` },
  ...[0, 1, 2, 3, 4].map(field => ({ id: `field-${field}`, type: 'input', props: { label: `Answer ${index} field ${field + 1}` }, bindings: { value: `/field${field}` } })),
  { id: `submit-${index}`, type: 'button', props: { type: 'submit' }, text: 'Submit review', ...(index === 25 ? { action: { name: 'review-session', payload: { messageId: 'retained-message-25', cycle } } } : {}) },
] });
async function archiveFixture(cycle = 1) {
  const [runtime, catalogLibrary, chat, authoring] = await Promise.all(['runtime', 'catalog', 'chat', 'authoring'].map(name => loadLibrary(`@aceshooting/lyra-gen/${name}.js`)));
  const catalog = catalogLibrary.createCatalog({ ...catalogLibrary.initialCatalog, actions: { 'review-session': { payload: { type: 'object', properties: {
    messageId: { type: 'string' }, cycle: { type: 'integer' },
  }, required: ['messageId', 'cycle'], additionalProperties: false } } } });
  const recording = JSON.parse(await readFile(new URL('../../../packages/lyra-gen/examples/recordings/chat-review.v1.json', import.meta.url), 'utf8'));
  const messages = [];
  for (let index = 0; index <= 50; index++) {
    if (index < 50 && index % 5 !== 0) { messages.push({ index, parts: [{ id: `retained-message-${index}:body`, type: 'text', state: 'complete', text: memoryChatText(index) }], islands: [] }); continue; }
    const controller = chat.createChatStream({ messageId: `retained-message-${index}`, surfaceId: `retained-surface-${index}`, catalog,
      provenance: 'Generated by the assistant', strings: { loading: 'Loading', invalid: 'Invalid', incomplete: 'Incomplete', sourceUnavailable: 'Unavailable' } });
    if (index === 50) for (const chunk of recording.chunks) controller.push(chunk.text);
    else {
      const markup = authoring.emitMarkup({ version: '1', surfaceId: 'authored-form', revision: 0, catalog: { id: catalog.id, version: catalog.version }, root: form(index, cycle) }, catalog);
      assert.equal(markup.ok, true);
      controller.push(`${memoryChatText(index)}\`\`\`lyra\n${markup.value}\n\`\`\`\n`);
    }
    controller.finish();
    const snapshot = controller.snapshot;
    assert.equal(snapshot.status, 'complete');
    messages.push({ index, parts: snapshot.parts, islands: snapshot.islands.map(island => {
      let state = runtime.createSurfaceState(island.document);
      if (index === 25) { const edited = runtime.setSurfaceState(state, '/field2', expectedNote(cycle)); assert.equal(edited.ok, true); state = edited.value; }
      return { partId: island.partId, snapshot: runtime.createSnapshot(island.document, state) };
    }) });
    controller.dispose();
  }
  return { runtime, catalog, archive: { version: 1, cycle, actions: 1, selection: [expectedNote(cycle).length, expectedNote(cycle).length], scrollTop: 0, following: false, messages } };
}

test('all five memory projections retain full L and exactly two intended actions', () => {
  for (const phase of ['mounted', 'released', 'restored']) {
    const expected = expectedMemoryApplication(phase, { cycle: 7 });
    assert.deepEqual([expected.messages, expected.islands, expected.baseCharacters], [51, 12, 51200]);
    assert.equal(expected.editedValue, 'Edited note 0007'); assert.deepEqual(expected.dirtyPaths, ['/field2']);
    assert.equal(expected.middleRevision, phase === 'restored' ? 1 : 0); assert.equal(expected.actions, 1);
    assert.equal(expected.sourceReleased, phase !== 'mounted');
  }
  for (const phase of ['disposed', 'restored-disposed']) {
    const expected = expectedMemoryApplication(phase, { cycle: 7 });
    assert.deepEqual([expected.messages, expected.islands, expected.baseCharacters], [0, 0, 0]);
    assert.equal(expected.actions, phase === 'disposed' ? 1 : 2);
  }
  for (const index of Array.from({ length: 50 }, (_, index) => index)) {
    assert.equal(memoryChatText(index).length, 1024);
    if (index % 5 === 0) { assert.deepEqual(memoryChatTree(index, 7), form(index, 7)); assert.equal(memoryChatTree(index, 7).children.length + 1, 8); }
  }
  assert.throws(() => expectedMemoryApplication('unknown', { cycle: 1 })); assert.throws(() => expectedMemoryApplication('mounted', { cycle: 41 }));
});

test('actual public chat/controller snapshots archive all51messages and12islands with independently authored forms', async () => {
  const { archive, runtime, catalog } = await archiveFixture(7);
  assert.equal(validateMemoryChatArchive(archive, 7), archive);
  assert.equal(archive.messages.length, 51); assert.equal(archive.messages.flatMap(message => message.islands).length, 12);
  assert.equal(archive.messages.slice(0, 50).flatMap(message => message.parts.filter(part => part.type === 'text')).reduce((sum, part) => sum + part.text.length, 0), 51200);
  assert.ok(Buffer.byteLength(JSON.stringify(archive)) < 512 * 1024);
  const saved = archive.messages[25].islands[0].snapshot;
  const restored = runtime.restoreSnapshot(saved, catalog); assert.equal(restored.ok, true);
  const next = structuredClone(saved.view); next.revision = 1;
  next.root.children.find(child => child.id === 'field-2').props.value = 'Higher generated default';
  const reconciled = runtime.reconcileSurfaceState(restored.value.state, restored.value.view, next);
  assert.equal(reconciled.ok, true); assert.equal(reconciled.value.values.field2, 'Edited note 0007'); assert.deepEqual(reconciled.value.dirty, ['/field2']);
  assert.deepEqual(reconciled.value.owners['/field2'], { nodeId: 'field-2', property: 'value', type: 'input' });
});

