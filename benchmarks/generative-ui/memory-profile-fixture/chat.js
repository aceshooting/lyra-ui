const require = (condition, message) => { if (!condition) throw new Error(message); };
const canonical = value => JSON.stringify(value, (_key, item) => item && typeof item === 'object' && !Array.isArray(item)
  ? Object.fromEntries(Object.entries(item).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) : item);
const phases = ['mounted', 'released', 'disposed', 'restored', 'restored-disposed'];
const provenance = 'Generated by the assistant';
const recordedProse = ['Review follows.\n\n', 'The first review field is ready.\n\n', 'Replay complete.'];
export const memoryChatText = index => index % 5 === 0 ? `${ascii(index).slice(0, -1)}\n` : ascii(index);
const action = cycle => ({ name: 'review-session', payload: { messageId: 'retained-message-25', cycle } });
export function memoryChatTree(index, cycle, higher = false) {
  require(Number.isInteger(index) && index >= 0 && index < 50 && index % 5 === 0, 'Invalid retained form index.');
  const root = expectedChatTrees.form(index);
  if (index !== 25) return root;
  return { ...root, children: root.children.map(child => child.id === 'submit-25' ? { ...child, action: action(cycle) }
    : higher && child.id === 'field-2' ? { ...child, props: { ...child.props, value: 'Higher generated default' } } : child) };
}
export function expectedMemoryApplication(phase, { cycle }) {
  require(phases.includes(phase) && Number.isSafeInteger(cycle) && cycle > 0 && cycle <= 40, 'Invalid chat memory phase or cycle.');
  const gone = phase.includes('disposed');
  return { application: 'full-chat', phase, cycle, messages: gone ? 0 : 51, islands: gone ? 0 : 12, baseCharacters: gone ? 0 : 51200,
    editedValue: gone ? '' : expectedNote(cycle), dirtyPaths: gone ? [] : ['/field2'], middleRevision: gone ? null : phase === 'restored' ? 1 : 0,
    actions: phase === 'restored-disposed' ? 2 : 1, sourceReleased: phase !== 'mounted', panel: false, following: false };
}
const ownersForForm = () => Object.fromEntries(Array.from({ length: 5 }, (_, index) => [`/field${index}`, { nodeId: `field-${index}`, property: 'value', type: 'input' }]));
export function validateMemoryChatArchive(value, cycle) {
  require(value && Object.keys(value).sort().join(',') === 'actions,cycle,following,messages,scrollTop,selection,version'
    && value.version === 1 && value.cycle === cycle && value.actions === 1 && value.following === false
    && Number.isFinite(value.scrollTop) && value.scrollTop >= 0 && value.scrollTop <= 1, 'Invalid chat memory archive.');
  require(Array.isArray(value.selection) && value.selection.length === 2 && value.selection.every(position => Number.isSafeInteger(position)
    && position >= 0 && position <= expectedNote(cycle).length) && value.selection[0] <= value.selection[1], 'Invalid archived input selection.');
  require(Array.isArray(value.messages) && value.messages.length === 51, 'Archive must retain all fifty-one messages.');
  for (const [index, message] of value.messages.entries()) {
    require(message.index === index && Object.keys(message).sort().join(',') === 'index,islands,parts'
      && Array.isArray(message.parts) && Array.isArray(message.islands), 'Invalid archived message.');
    const expectedIslands = index === 50 ? 2 : index % 5 === 0 ? 1 : 0;
    const texts = message.parts.filter(part => part.type === 'text').map(part => part.text);
    require(canonical(texts) === canonical(index === 50 ? recordedProse : [memoryChatText(index)])
      && message.islands.length === expectedIslands && message.parts.length === (index === 50 ? 5 : expectedIslands ? 2 : 1)
      && new Set(message.parts.map(part => part.id)).size === message.parts.length
      && message.parts.every(part => part.state === 'complete' && typeof part.id === 'string' && part.id.startsWith(`retained-message-${index}:`)), 'Archived presentation changed.');
    for (const [islandIndex, island] of message.islands.entries()) {
      require(Object.keys(island).sort().join(',') === 'partId,snapshot' && message.parts.some(part => part.type === 'data'
        && part.name === 'lyra-gen-island' && part.id === island.partId), 'Archived island part changed.');
      const snapshot = island.snapshot, surfaceId = `retained-surface-${index}:island-${islandIndex}`;
      const root = index === 50 ? islandIndex === 0 ? expectedChatTrees.review : expectedChatTrees.detail : memoryChatTree(index, cycle);
      const owners = index === 50 ? islandIndex === 0 ? { '/note': { nodeId: 'note', property: 'value', type: 'input' } } : {} : ownersForForm();
      require(snapshot?.version === '1' && canonical(snapshot.view) === canonical({ version: '1', catalog: { id: 'lyra-reviewed', version: '1' }, surfaceId, revision: 0, root })
        && canonical(snapshot.state) === canonical({ surfaceId, revision: 0, owners, values: index === 25 ? { field2: expectedNote(cycle) } : {}, dirty: index === 25 ? ['/field2'] : [] }), 'Archived view or dirty ownership changed.');
      const part = message.parts.find(part => part.id === island.partId), data = part.data;
      require(data?.kind === 'lyra-gen-island' && data.partId === island.partId && data.surfaceId === surfaceId
        && data.status === 'ready' && data.fallback === '' && data.provenance === provenance && canonical(data.document) === canonical(snapshot.view), 'Archived neutral island differs from its accepted view.');
    }
  }
  require(new TextEncoder().encode(JSON.stringify(value)).length <= 524288, 'Chat archive exceeds the shared archive ceiling.');
  return value;
}
export function validateMemoryChatAction(detail, { cycle, higher, actions }) {
  require(detail?.surfaceId === 'retained-surface-25:island-0' && detail.nodeId === 'submit-25' && detail.revision === (higher ? 1 : 0)
    && detail.name === 'review-session' && canonical(detail.payload) === canonical(action(cycle).payload)
    && actions === (higher ? 1 : 0), 'Unexpected or replayed chat memory action.');
}
export function memoryChatEventView(event, views) {
  const origin = event.composedPath()[0];
  return views.includes(origin) && origin.document?.surfaceId === event.detail?.surfaceId ? origin : undefined;
}
export function validateMemoryChatActionOrigin(event, views, middle) {
  const origin = memoryChatEventView(event, views);
  require(origin !== undefined && origin === middle, 'Foreign chat action.');
}
