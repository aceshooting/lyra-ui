function nativeInput(view, id) { return deep(view.shadowRoot, `[data-gen-id="${id}"]`)?.shadowRoot?.querySelector('input'); }
export function matchesRenderedTree(view, expected, values = {}) {
  if (view.status !== 'ready' || canonical(view.document?.root) !== canonical(expected)) return false;
  const nodes = view.shadowRoot?.querySelectorAll('[data-gen-id]');
  const visit = item => [item, ...(item.children ?? []).flatMap(visit)];
  const all = visit(expected);
  return nodes?.length === all.length && all.every(item => {
    const element = [...nodes].find(candidate => candidate.dataset.genId === item.id);
    if (!element || element.localName !== tags[item.type]) return false;
    if (item.text !== undefined && element.textContent !== item.text) return false;
    if (item.props?.label !== undefined && (element.label !== item.props.label || !deep(element.shadowRoot, 'input'))) return false;
    if (item.type === 'input' && nativeInput(view, item.id)?.value !== (values[item.bindings.value.slice(1)] ?? '')) return false;
    if (item.props?.type !== undefined && element.type !== item.props.type) return false;
    const children = [...element.children].filter(child => child.hasAttribute('data-gen-id'));
    return encode(children.map(child => child.dataset.genId)) === encode((item.children ?? []).map(child => child.id));
  });
}
const renderedTree = matchesRenderedTree;
function exactProse(body, expected) {
  const rendered = [...(body.shadowRoot?.querySelectorAll('[data-type="text"]') ?? [])];
  return encode(rendered.map(element => element.textContent)) === encode(expected);
}
