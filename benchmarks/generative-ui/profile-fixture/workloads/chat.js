function validateRecording(recording) {
  if (recording?.text?.length !== 379 || !/^[\x00-\x7f]*$/u.test(recording.text)
    || encode(recording.chunks?.map(chunk => chunk.atMs)) !== encode(cadence)
    || recording.chunks.map(chunk => chunk.text).join('') !== recording.text) throw new Error('Unexpected chat recording.');
  return recording;
}

